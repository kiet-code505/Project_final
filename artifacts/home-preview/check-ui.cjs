const fs = require('node:fs');
const assert = require('node:assert/strict');
const WebSocket = require('D:/Đồ án cuối kì/frontend/node_modules/ws');
(async () => {
  const tabs = await (await fetch('http://localhost:9239/json')).json();
  const tab = tabs.find(t => t.type === 'page');
  const socket = new WebSocket(tab.webSocketDebuggerUrl);
  await new Promise((resolve, reject) => { socket.addEventListener('open', resolve, { once: true }); socket.addEventListener('error', reject, { once: true }); });
  let id = 0; const pending = new Map();
  socket.addEventListener('message', event => { const message = JSON.parse(event.data); if (message.id) { const callback = pending.get(message.id); pending.delete(message.id); message.error ? callback.reject(message.error) : callback.resolve(message.result); } });
  const send = (method, params = {}) => new Promise((resolve, reject) => { const key = ++id; pending.set(key, {resolve, reject}); socket.send(JSON.stringify({id:key, method, params})); });
  const evaluate = async expression => { const result = await send('Runtime.evaluate', {expression, returnByValue:true, awaitPromise:true}); if (result.exceptionDetails) throw new Error(JSON.stringify(result.exceptionDetails)); return result.result.value; };
  const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
  await send('Page.enable');
  await send('Emulation.setDeviceMetricsOverride', {width:1440, height:1100, deviceScaleFactor:1, mobile:false});
  await send('Page.navigate', {url:'http://localhost:5029/'});
  for (let i=0; i<80; i++) { if (await evaluate('document.readyState === "complete" && !!document.querySelector("[data-tour-dialog]")')) break; await pause(150); }
  assert.equal(await evaluate('!!document.querySelector("#products")'), true);
  assert.equal(await evaluate('document.documentElement.scrollWidth <= innerWidth'), true, 'desktop overflow');
  await evaluate('document.getElementById("tab-SOUTH").click()');
  assert.equal(await evaluate('!document.getElementById("region-SOUTH").hidden && document.getElementById("region-NORTH").hidden'), true);
  await evaluate('document.getElementById("tab-SOUTH").dispatchEvent(new KeyboardEvent("keydown", {key:"Home", bubbles:true}))');
  assert.equal(await evaluate('document.getElementById("tab-NORTH").getAttribute("aria-selected")'), 'true');
  await evaluate('document.querySelector("[data-tour-dialog]").click()');
  assert.equal(await evaluate('!!document.querySelector("dialog[open]")'), true);
  await evaluate('document.querySelector("dialog[open]").close()');
  await evaluate('document.querySelectorAll("[data-carousel]")[1].click()');
  await pause(800);
  assert.equal(await evaluate('document.getElementById("featured-tours").scrollLeft > 0'), true);
  await evaluate('document.getElementById("special-tours").scrollIntoView()');
  await pause(800);
  fs.writeFileSync(__dirname + '/home-special-desktop.png', Buffer.from((await send('Page.captureScreenshot', {format:'png'})).data, 'base64'));
  await send('Emulation.setDeviceMetricsOverride', {width:390,height:844,deviceScaleFactor:1,mobile:true});
  await evaluate('window.scrollTo(0,0)');
  await pause(1000);
  assert.equal(await evaluate('document.documentElement.scrollWidth <= innerWidth'), true, 'mobile overflow');
  await evaluate('document.querySelector(".menu-toggle").click()');
  assert.equal(await evaluate('document.querySelector(".menu-toggle").getAttribute("aria-expanded")'), 'true');
  await evaluate('document.querySelector("#user-navigation a").click()');
  await pause(800);
  await evaluate('window.scrollTo(0,0)');
  await pause(500);
  fs.writeFileSync(__dirname + '/home-mobile.png', Buffer.from((await send('Page.captureScreenshot', {format:'png'})).data, 'base64'));
  console.log('PASS desktop/mobile overflow, region tabs and keyboard navigation, tour dialog, carousel, mobile menu');
  await send('Browser.close');
})().catch(error => { console.error(error); process.exit(1); });
