const fs = require('node:fs');
const assert = require('node:assert/strict');
const WebSocket = require('D:/Đồ án cuối kì/frontend/node_modules/ws');
(async () => {
  const targets = await (await fetch('http://localhost:9240/json')).json();
  const socket = new WebSocket(targets.find(t => t.type === 'page').webSocketDebuggerUrl);
  await new Promise((resolve, reject) => { socket.addEventListener('open', resolve, {once:true}); socket.addEventListener('error', reject, {once:true}); });
  let id=0; const pending = new Map();
  socket.addEventListener('message', event => { const message=JSON.parse(event.data); if(message.id) { const handler=pending.get(message.id); pending.delete(message.id); message.error ? handler.reject(message.error) : handler.resolve(message.result); } });
  const send = (method,params={}) => new Promise((resolve,reject) => { const key=++id; pending.set(key,{resolve,reject}); socket.send(JSON.stringify({id:key,method,params})); });
  const evaluate = async expression => { const r=await send('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true}); if(r.exceptionDetails) throw new Error(JSON.stringify(r.exceptionDetails)); return r.result.value; };
  const pause = ms => new Promise(resolve=>setTimeout(resolve,ms));
  const waitPage = async () => { for(let i=0;i<100;i++) { if(await evaluate('document.readyState === "complete" && !!document.getElementById("filter-toggle")')) { await pause(300); return; } await pause(150); } throw new Error('Page did not load'); };
  const navigate = async path => { await send('Page.navigate',{url:'http://localhost:5030'+path}); await pause(300); await waitPage(); };
  await send('Page.enable');
  await send('Emulation.setDeviceMetricsOverride',{width:1440,height:1050,deviceScaleFactor:1,mobile:false});
  await navigate('/tours');
  assert.equal(await evaluate('document.documentElement.scrollWidth <= innerWidth'),true,'desktop overflow');
  assert.equal(await evaluate('document.querySelectorAll(".tour-search .tourCard").length > 0'),true);
  assert.equal(await evaluate('document.querySelector("#user-navigation a.active").textContent'),'Chuyến đi');
  fs.writeFileSync(__dirname+'/search-desktop.png',Buffer.from((await send('Page.captureScreenshot',{format:'png'})).data,'base64'));
  await evaluate('document.getElementById("filter-toggle").click()');
  assert.equal(await evaluate('document.getElementById("tour-filter-panel").hidden'),false);
  await evaluate('document.querySelector("input[value=under5]").checked=true; document.getElementById("tour-filter-panel").requestSubmit()');
  await pause(500); await waitPage();
  assert.equal(await evaluate('new URL(location.href).searchParams.get("budget")'),'under5');
  assert.equal(await evaluate('[...document.querySelectorAll(".tourCard[data-price]")].every(c=>c.dataset.price !== "" && Number(c.dataset.price) < 5000000)'),true,'budget filter');
  await evaluate('document.querySelector(".filterChip").click()');
  await pause(500); await waitPage();
  assert.equal(await evaluate('new URL(location.href).searchParams.has("budget")'),false,'chip removal');
  await navigate('/tours?sort=price-asc');
  assert.equal(await evaluate('(()=>{ const prices=[...document.querySelectorAll(".tourCard[data-price]")].map(c=>c.dataset.price === "" ? Infinity : Number(c.dataset.price)); return prices.every((p,i)=>i===0 || p>=prices[i-1]); })()'),true,'price sort');
  await evaluate('document.querySelector("[data-tour-dialog]").click()');
  assert.equal(await evaluate('!!document.querySelector("dialog[open]")'),true);
  await evaluate('document.querySelector("dialog[open]").close()');
  await navigate('/tours?budget=5to10&sort=price-desc&page=2');
  assert.equal(await evaluate('[...document.querySelectorAll(".search-pagination a")].every(a=>new URL(a.href).searchParams.get("budget")==="5to10" && new URL(a.href).searchParams.get("sort")==="price-desc")'),true,'pagination retains filters');
  await navigate('/tours?searchNameTour=NO_MATCH_TOUR_2026');
  assert.equal(await evaluate('!!document.querySelector(".emptyState")'),true);
  await navigate('/tours');
  await send('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true});
  await evaluate('window.scrollTo(0,0)'); await pause(700);
  assert.equal(await evaluate('document.documentElement.scrollWidth <= innerWidth'),true,'mobile overflow');
  await evaluate('document.getElementById("filter-toggle").click()');
  assert.equal(await evaluate('document.getElementById("tour-filter-panel").getBoundingClientRect().right <= innerWidth'),true,'mobile filter panel');
  await evaluate('document.getElementById("filter-toggle").click()');
  fs.writeFileSync(__dirname+'/search-mobile.png',Buffer.from((await send('Page.captureScreenshot',{format:'png'})).data,'base64'));
  console.log('PASS desktop/mobile layout, header, filter panel, budget results, chip removal, price sort, tour dialog, pagination filters, empty state');
  await send('Browser.close');
})().catch(error=>{console.error(error);process.exit(1);});
